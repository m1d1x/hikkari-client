// Package svcproto is the contract between the unprivileged GUI engine and
// the hikkari service that owns the VPN core — sing-box or Xray, whichever
// engine the user chose (core/service: a Windows service behind a named
// pipe, a macOS LaunchDaemon behind a unix socket).
//
// One request per connection, one JSON line each way:
//
//	GUI ──{"op":"start","engine":…,"config":{…}}──▶ service   sanitise, write, run core
//	GUI ──{"op":"autotunnel","hosts":[…]}──────▶ service   rewrite the core's autotunnel rule set
//	GUI ──{"op":"stop"}─────────────────▶ service      stop core
//	GUI ──{"op":"status"}───────────────▶ service      running? core log? update state?
//	GUI ──{"op":"check_update"}─────────▶ service      poll the channel now (throttled)
//	launcher ──{"op":"apply_update"}────▶ service      stop core, swap in the staged version; a wanted core stays down for the new GUI's start
//	launcher ──{"op":"recover_update"}──▶ service      at every launch: repair / trial / roll back
//	launcher ──{"op":"confirm_update"}──▶ service      the new version runs: keep it
//	launcher ──{"op":"rollback_update"}─▶ service      the new version died: put the old back
//
// The package is platform-neutral on purpose: the sanitiser is the security
// boundary of the whole split, and it has to be testable on any machine.
package svcproto

import (
	"bufio"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"strings"
)

// PipeName is the service's control pipe on Windows.
const PipeName = `\\.\pipe\hikkari-service`

// SocketPath is the service's control socket on macOS.
const SocketPath = "/var/run/hikkari-service.sock"

// ServiceName is the SCM name of the service.
const ServiceName = "HikkariService"

// MaxMessage bounds one request or response. A generated config is tens of
// kilobytes; anything near this is not one.
const MaxMessage = 4 << 20

// Engines the service can run. One core runs at a time: starting one stops
// the other.
const (
	EngineSingBox = "sing-box"
	EngineXray    = "xray"
)

// SingBoxDNS is the address the core hijacks DNS on: the next one after its
// TUN address (configfile.tunInbound), which sing-tun picks by itself.
const SingBoxDNS = "172.19.0.2"

// Ops.
const (
	OpStart  = "start"
	OpStop   = "stop"
	OpStatus = "status"

	OpCheckUpdate    = "check_update"
	OpApplyUpdate    = "apply_update"
	OpRecoverUpdate  = "recover_update"
	OpConfirmUpdate  = "confirm_update"
	OpRollbackUpdate = "rollback_update"

	// OpResetNetwork resets the OS network stack: Winsock and TCP/IP on
	// Windows (`netsh winsock reset`, `netsh int ip reset`), the routing
	// table on macOS. See NetworkReset.
	OpResetNetwork = "reset_network"
	// OpRepairNetwork is the soft repair where its settings belong to the
	// machine (macOS). The service decides what is orphaned; see
	// NetworkRepair.
	OpRepairNetwork = "repair_network"
	// OpScanNetwork looks, read-only, for what the deep reset would deal
	// with and what nothing should touch; see NetworkScan.
	OpScanNetwork = "scan_network"

	// OpAutoTunnel replaces the autotunnel host list (core/autotunnel). The
	// list travels as data; the service owns the rule set file the core
	// reads and rewrites the config's rule set path to it — see Sanitize.
	OpAutoTunnel = "autotunnel"
)

// CodeAppReplaced: the GUI runs a release other than the installed one (an
// update or a rollback replaced the installation under it). Nothing was
// changed; the GUI reopens itself from the installation.
const CodeAppReplaced = "app_replaced"

type Request struct {
	Op string `json:"op"`
	// Engine, for OpStart: which core Config is for. Empty is sing-box, so
	// a GUI from before Xray keeps working.
	Engine string `json:"engine,omitempty"`
	// Config is the core's config for OpStart, as generated by the GUI
	// engine. The service never runs it as given — see Sanitize and
	// SanitizeXray.
	Config json.RawMessage `json:"config,omitempty"`
	// ConfigHash, for OpStart: the GUI's fingerprint of what Config means, taken
	// before the parts that differ from start to start (see
	// configfile.Store.Fingerprint). The service keeps it beside the config and
	// answers with it: it cannot compute it, since it sees Config only after the
	// server addresses are pinned.
	ConfigHash string `json:"configHash,omitempty"`
	// AppVersion, for OpStart: the release the GUI was started from
	// (core/appversion), empty for a development build or a GUI from before
	// it was sent. The service compares it with the installation's VERSION
	// and refuses a start from another release (CodeAppReplaced): a config
	// of another release may name fields the installed core does not know.
	AppVersion string `json:"appVersion,omitempty"`
	// Restarting, for OpStop: a start follows at once, so the wish to be up
	// stays. If that start fails the GUI keeps trying (Response.Wanted).
	Restarting bool `json:"restarting,omitempty"`
	// Hosts, for OpAutoTunnel: the whole autotunnel host list. The service
	// validates it and writes its own rule set file from it.
	Hosts []string `json:"hosts,omitempty"`
	// Reconnect, for OpApplyUpdate: the tunnel was up when the user asked
	// to restart, so bring the core back on the new version right away.
	Reconnect bool `json:"reconnect,omitempty"`
	// Force, for OpResetNetwork: reset even though adapters with a static
	// IPv4 configuration would lose it. The user confirmed that explicitly.
	Force bool `json:"force,omitempty"`
	// ProxyOnly, for OpRepairNetwork: only the system proxy, as before a
	// connect.
	ProxyOnly bool `json:"proxyOnly,omitempty"`
}

type Response struct {
	OK    bool   `json:"ok"`
	Error string `json:"error,omitempty"`
	// Code names a refusal the GUI acts on (Code* below); empty for any
	// other error.
	Code string `json:"code,omitempty"`
	// Status fields.
	Running bool `json:"running,omitempty"`
	Pid     int  `json:"pid,omitempty"`
	// Engine is the core that is running (empty when none is).
	Engine  string `json:"engine,omitempty"`
	CoreLog string `json:"coreLog,omitempty"`
	Version string `json:"version,omitempty"`
	// ConfigTracked: this service records which version of itself received the
	// stored config. ConfigVersion is that version, empty for a config written
	// before it did. A service replaced by an update resumes the core on the old
	// config, so a difference from Version means the core runs rules of an older
	// release, however new the GUI's own copy is.
	ConfigTracked bool   `json:"configTracked,omitempty"`
	ConfigVersion string `json:"configVersion,omitempty"`
	// Supervised: this service answers Wanted and ConfigHash, and after an update
	// waits for the GUI's config instead of resuming the core on the old one.
	Supervised bool `json:"supervised,omitempty"`
	// Wanted: the core should be up (the run marker). Wanted without Running is
	// a core waiting for the new release's config, or a start that failed: the
	// GUI starts it.
	Wanted bool `json:"wanted,omitempty"`
	// ConfigHash is the Request.ConfigHash the stored config came with; empty for
	// a config stored without one.
	ConfigHash string `json:"configHash,omitempty"`

	Update *UpdateState `json:"update,omitempty"`
	// SyncsBinaries: this service keeps the binaries outside the replaced
	// tree up to date itself (Windows: hikkari.exe, HikkariService.exe,
	// hikkari-updater.exe beside app\). A service from before that (1.0.x)
	// leaves it to the GUI, which has one elevated run of the new service
	// binary adopt them.
	SyncsBinaries bool `json:"syncsBinaries,omitempty"`
	// ScanSafe: OpScanNetwork cannot take this service down. A new GUI runs
	// against the previous service until the update is confirmed; 1.0.18 died
	// on the scan, and the tunnel with it, so a service without this is not
	// asked.
	ScanSafe bool `json:"scanSafe,omitempty"`
	// Recovery, for OpRecoverUpdate: nothing | repaired | on_trial | rolled_back.
	Recovery string `json:"recovery,omitempty"`
	// From / To: the versions an apply, recovery or rollback moved between.
	From string `json:"from,omitempty"`
	To   string `json:"to,omitempty"`

	NetworkReset  *NetworkReset  `json:"networkReset,omitempty"`
	NetworkScan   *NetworkScan   `json:"networkScan,omitempty"`
	NetworkRepair *NetworkRepair `json:"networkRepair,omitempty"`
}

// NetworkRepair is the outcome of OpRepairNetwork.
type NetworkRepair struct {
	Actions []NetworkAction `json:"actions"`
}

// NetworkAction is one repair step. Done is false when it was skipped or
// failed; Detail says which.
type NetworkAction struct {
	Name   string `json:"name"`
	Done   bool   `json:"done"`
	Detail string `json:"detail,omitempty"`
}

// NetworkScan is the outcome of OpScanNetwork.
type NetworkScan struct {
	// HostsOverrides counts hosts entries that override protected domains,
	// -1 when the file could not be read.
	HostsOverrides int `json:"hostsOverrides"`
	// DPITools are the classes (winws, goodbyedpi, windivert) of DPI tools
	// the deep reset would stop. Null when they could not be checked, which
	// is also what a GUI reads from a service older than this field; empty
	// when none were found.
	DPITools []string `json:"dpiTools"`
	// ForeignWFP names the firewall owners that are not the system's, for
	// the report only: nothing removes them. WFP providers on Windows, pf
	// anchors of an enabled pf on macOS. Null and empty as for DPITools.
	ForeignWFP []string `json:"foreignWfp"`
	// WinDivert is nil when the machine has no such driver.
	WinDivert *WinDivertState `json:"winDivert,omitempty"`
}

// WinDivertState says whether a WinDivert driver can be touching packets: it
// does so only while running and held open by a program.
type WinDivertState struct {
	Running bool `json:"running"`
	// Holders are the executables with WinDivert loaded. Null when they could
	// not be listed.
	Holders []string `json:"holders"`
}

// LogValue renders the state for a log line.
func (w *WinDivertState) LogValue() string {
	if w == nil {
		return "none"
	}
	state := "stopped"
	if w.Running {
		state = "running"
	}
	return state + " held by " + ScanList(w.Holders)
}

// ScanList renders a NetworkScan list for a log line, keeping "could not
// check" apart from "none found".
func ScanList(items []string) string {
	switch {
	case items == nil:
		return "unknown"
	case len(items) == 0:
		return "none"
	}
	return strings.Join(items, ", ")
}

// NetworkReset is the outcome of OpResetNetwork.
type NetworkReset struct {
	// Refused: nothing was changed, because StaticAdapters would lose
	// their manual addresses. Repeat with Force after the user agrees.
	Refused bool `json:"refused,omitempty"`
	// StaticAdapters are the connected adapters configured with a static
	// IPv4 address, by friendly name.
	StaticAdapters []string `json:"staticAdapters,omitempty"`
	// RebootRequired: the reset ran; Windows applies it on the next boot.
	// macOS applies it at once.
	RebootRequired bool `json:"rebootRequired,omitempty"`
	// NetworkPending: the reset ran, but the network was not back when the
	// service stopped waiting for it (macOS). It may still come up.
	NetworkPending bool `json:"networkPending,omitempty"`
	// Output is what netsh printed, for the diagnostic log.
	Output string `json:"output,omitempty"`
	// HostsDisabled counts hosts entries commented out (backup kept).
	HostsDisabled int `json:"hostsDisabled,omitempty"`
	// DPIStopped are the classes of DPI tools stopped or moved to manual
	// start; the original start types are in core\netreset-backup.json.
	DPIStopped []string `json:"dpiStopped,omitempty"`
	// DPIFailed are the classes still running or still starting by
	// themselves. The reset itself went on without them.
	DPIFailed []string `json:"dpiFailed,omitempty"`
}

// Update states, as the GUI shows them.
const (
	UpdateIdle        = "idle"        // up to date as of CheckedAt
	UpdateDownloading = "downloading" // staging a new version
	UpdateReady       = "ready"       // staged; applies on «Перезапустить»
	UpdateError       = "error"       // the last attempt failed; retried on schedule
	UpdateUnavailable = "unavailable" // this build has no update channel
)

type UpdateState struct {
	State     string `json:"state"`
	Installed string `json:"installed,omitempty"`
	// Version is the staged (or downloading) release.
	Version   string `json:"version,omitempty"`
	Mandatory bool   `json:"mandatory,omitempty"`
	BytesDone int64  `json:"bytesDone,omitempty"`
	BytesAll  int64  `json:"bytesTotal,omitempty"`
	Error     string `json:"error,omitempty"`
	// CheckedAt is the last completed check, unix seconds.
	CheckedAt int64 `json:"checkedAt,omitempty"`
	// Replaced is the GUI engine's own finding, never the service's: the
	// process runs a release other than Installed — an update or a rollback
	// replaced the installation under it. The GUI reopens itself
	// (Core.RelaunchApp).
	Replaced bool `json:"replaced,omitempty"`
}

// WriteMessage writes v as one JSON line.
func WriteMessage(w io.Writer, v interface{}) error {
	b, err := json.Marshal(v)
	if err != nil {
		return err
	}
	if len(b) > MaxMessage {
		return fmt.Errorf("message is %d bytes, limit %d", len(b), MaxMessage)
	}
	_, err = w.Write(append(b, '\n'))
	return err
}

// ReadMessage reads one JSON line into v, refusing anything over MaxMessage.
func ReadMessage(r io.Reader, v interface{}) error {
	br := bufio.NewReader(io.LimitReader(r, MaxMessage+1))
	line, err := br.ReadBytes('\n')
	switch {
	case len(line) > MaxMessage:
		return fmt.Errorf("message over %d bytes", MaxMessage)
	case err != nil && !(errors.Is(err, io.EOF) && len(line) > 0):
		return err
	}
	return json.Unmarshal(line, v)
}
